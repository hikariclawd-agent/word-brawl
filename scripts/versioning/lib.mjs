import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

export const rootDir = path.resolve(import.meta.dirname, '..', '..');
export const mobilePackagePath = path.join(rootDir, 'apps/mobile/package.json');
export const mobileAppJsonPath = path.join(rootDir, 'apps/mobile/app.json');
export const buildMetadataPath = path.join(rootDir, 'apps/mobile/src/generated/buildMetadata.ts');
export const releaseManifestDir = path.join(rootDir, 'release-manifests');

export function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

export function getMobileMetadata() {
  const mobilePackage = readJson(mobilePackagePath);
  const mobileApp = readJson(mobileAppJsonPath);
  const expo = mobileApp.expo ?? {};
  const appVersion = mobilePackage.version;
  const appJsonVersion = expo.version;
  const iosBuildNumber = expo.ios?.buildNumber;
  const androidVersionCode = expo.android?.versionCode;

  return {
    appVersion,
    appJsonVersion,
    iosBuildNumber,
    androidVersionCode,
    buildIdentifier: `ios:${iosBuildNumber ?? 'missing'}/android:${androidVersionCode ?? 'missing'}`,
  };
}

export function getGitCommit() {
  if (process.env.WORD_BRAWL_GIT_COMMIT) return process.env.WORD_BRAWL_GIT_COMMIT;

  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: rootDir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return 'unknown';
  }
}

export function getGitDirtyState() {
  try {
    const status = execFileSync('git', ['status', '--short', '--', '.'], { cwd: rootDir, encoding: 'utf8' }).trim();
    return status ? 'dirty' : 'clean';
  } catch {
    return 'unknown';
  }
}

export function normalizeEnvironment(value = process.env.EXPO_PUBLIC_APP_ENV ?? process.env.APP_ENV ?? process.env.NODE_ENV) {
  if (value === 'production' || value === 'preview' || value === 'development') return value;
  if (value === 'prod') return 'production';
  if (value === 'dev' || value === 'test') return 'development';
  return process.env.NODE_ENV === 'production' ? 'production' : 'development';
}

export function getMigrationVersions() {
  const migrationsDir = path.join(rootDir, 'supabase/migrations');
  if (!fs.existsSync(migrationsDir)) return [];

  return fs
    .readdirSync(migrationsDir)
    .filter((name) => /^\d+_.+\.sql$/.test(name))
    .sort()
    .map((name) => name.replace(/\.sql$/, ''));
}

export function getManifestPath(version) {
  return path.join(releaseManifestDir, `${version}.json`);
}

export function getBuildMetadata({ buildDate } = {}) {
  const mobile = getMobileMetadata();

  return {
    appVersion: mobile.appVersion,
    buildIdentifier: mobile.buildIdentifier,
    buildDate: buildDate ?? process.env.WORD_BRAWL_BUILD_DATE ?? new Date().toISOString(),
    environment: normalizeEnvironment(),
    gitCommit: getGitCommit(),
  };
}

export function parseGeneratedBuildMetadata(source) {
  const readString = (key) => {
    const match = source.match(new RegExp(`${key}: "([^"]*)"`));
    return match?.[1] ?? null;
  };

  return {
    appVersion: readString('appVersion'),
    buildIdentifier: readString('buildIdentifier'),
    buildDate: readString('buildDate'),
    environment: readString('environment'),
    gitCommit: readString('gitCommit'),
  };
}

export function validateSemver(version) {
  return /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(version);
}

export function writeBuildMetadataFile(metadata) {
  fs.mkdirSync(path.dirname(buildMetadataPath), { recursive: true });
  fs.writeFileSync(
    buildMetadataPath,
    `// Generated by scripts/versioning/write-build-metadata.mjs.\n` +
      `// Run \`corepack pnpm version:metadata\` before building a release.\n` +
      `export const BUILD_METADATA = {\n` +
      `  appVersion: ${JSON.stringify(metadata.appVersion)},\n` +
      `  buildIdentifier: ${JSON.stringify(metadata.buildIdentifier)},\n` +
      `  buildDate: ${JSON.stringify(metadata.buildDate)},\n` +
      `  environment: ${JSON.stringify(metadata.environment)},\n` +
      `  gitCommit: ${JSON.stringify(metadata.gitCommit)},\n` +
      `} as const;\n`,
  );
}

export function checkVersionState() {
  const errors = [];
  const warnings = [];
  const mobile = getMobileMetadata();

  if (mobile.appVersion !== mobile.appJsonVersion) {
    errors.push(`apps/mobile/package.json version ${mobile.appVersion} does not match apps/mobile/app.json expo.version ${mobile.appJsonVersion}.`);
  }

  if (!validateSemver(mobile.appVersion)) {
    errors.push(`Mobile app version ${mobile.appVersion} is not valid semantic versioning.`);
  }

  if (!mobile.iosBuildNumber || !/^\d+$/.test(String(mobile.iosBuildNumber))) {
    errors.push('apps/mobile/app.json expo.ios.buildNumber must be present as a numeric string.');
  }

  if (!Number.isInteger(mobile.androidVersionCode) || mobile.androidVersionCode < 1) {
    errors.push('apps/mobile/app.json expo.android.versionCode must be present as a positive integer.');
  }

  const manifestPath = getManifestPath(mobile.appVersion);
  if (!fs.existsSync(manifestPath)) {
    errors.push(`Missing release manifest ${path.relative(rootDir, manifestPath)}.`);
  } else {
    const manifest = readJson(manifestPath);
    if (manifest.appVersion !== mobile.appVersion) {
      errors.push(`Release manifest appVersion ${manifest.appVersion} does not match mobile app version ${mobile.appVersion}.`);
    }
    if (manifest.buildIdentifier !== mobile.buildIdentifier) {
      errors.push(`Release manifest buildIdentifier ${manifest.buildIdentifier} does not match ${mobile.buildIdentifier}.`);
    }

    const migrations = getMigrationVersions();
    const manifestMigrations = Array.isArray(manifest.databaseMigrationsIncluded) ? manifest.databaseMigrationsIncluded : [];
    const missingFromManifest = migrations.filter((migration) => !manifestMigrations.includes(migration));
    if (missingFromManifest.length > 0) {
      errors.push(`Release manifest is missing migration versions: ${missingFromManifest.join(', ')}.`);
    }
  }

  if (!fs.existsSync(buildMetadataPath)) {
    errors.push(`Missing generated build metadata ${path.relative(rootDir, buildMetadataPath)}.`);
  } else {
    const generated = parseGeneratedBuildMetadata(fs.readFileSync(buildMetadataPath, 'utf8'));
    if (generated.appVersion !== mobile.appVersion) {
      errors.push(`Generated build metadata appVersion ${generated.appVersion} does not match mobile app version ${mobile.appVersion}.`);
    }
    if (generated.buildIdentifier !== mobile.buildIdentifier) {
      errors.push(`Generated build metadata buildIdentifier ${generated.buildIdentifier} does not match ${mobile.buildIdentifier}.`);
    }
    if (!generated.buildDate) {
      errors.push('Generated build metadata is missing buildDate.');
    }
    if (!['development', 'preview', 'production'].includes(generated.environment)) {
      errors.push(`Generated build metadata environment ${generated.environment} is invalid.`);
    }
  }

  if (getGitDirtyState() !== 'clean') {
    warnings.push('Git working tree has uncommitted changes; source changes are not released until committed, built, and installed.');
  }

  return { errors, warnings, mobile };
}
